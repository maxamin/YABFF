#!/usr/bin/env python3
"""A/B benchmark for the feroxbuster-ml native ML layer.

Runs the SAME binary and wordlist against a local target twice — once as stock
feroxbuster, once with `--ml` — and reports discovery and cost for each. The
delta is the ML layer's contribution.

Usage:
    scripts/ab_benchmark.py \
        --bin feroxbuster-ml/target/release/feroxbuster \
        --server bench/structured_server.py --port 8010 \
        --wordlist bench/ab-wordlist.txt \
        [--out docs/analysis/ml-ab-benchmark.md] [-- EXTRA ferox args]

Exit code is non-zero if the binary or server can't be started.
"""
import argparse
import json
import os
import signal
import socket
import subprocess
import sys
import tempfile
import time


def wait_port(port, timeout=5.0):
    deadline = time.time() + timeout
    while time.time() < deadline:
        try:
            with socket.create_connection(("127.0.0.1", port), 0.2):
                return True
        except OSError:
            time.sleep(0.05)
    return False


def run_scan(binary, target, wordlist, out_path, ml, extra):
    args = [binary, "-u", target, "-w", wordlist, "--json", "-o", out_path,
            "--silent", "--no-state"]
    if ml:
        args.append("--ml")
    args.extend(extra)
    t0 = time.time()
    subprocess.run(args, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=False)
    return time.time() - t0


def parse(out_path):
    found = set()
    stats = {}
    with open(out_path) as fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            try:
                obj = json.loads(line)
            except json.JSONDecodeError:
                continue
            if obj.get("type") == "response":
                found.add((obj.get("path", ""), obj.get("status", 0)))
            elif obj.get("type") == "statistics":
                stats = obj
    return found, stats


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--bin", required=True, help="path to the feroxbuster binary")
    ap.add_argument("--server", required=True, help="python target server script")
    ap.add_argument("--port", type=int, default=8010)
    ap.add_argument("--wordlist", required=True)
    ap.add_argument("--out", help="write a markdown report here")
    ap.add_argument("extra", nargs="*", help="extra args passed to both scans")
    args = ap.parse_args()

    for path in (args.bin, args.server, args.wordlist):
        if not os.path.exists(path):
            sys.exit(f"not found: {path}")

    server = subprocess.Popen([sys.executable, args.server, str(args.port)],
                              stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    try:
        if not wait_port(args.port):
            sys.exit("target server did not come up")
        target = f"http://127.0.0.1:{args.port}"

        with tempfile.TemporaryDirectory() as td:
            stock_out = os.path.join(td, "stock.json")
            ml_out = os.path.join(td, "ml.json")
            stock_dt = run_scan(args.bin, target, args.wordlist, stock_out, False, args.extra)
            ml_dt = run_scan(args.bin, target, args.wordlist, ml_out, True, args.extra)
            stock_found, stock_stats = parse(stock_out)
            ml_found, ml_stats = parse(ml_out)
    finally:
        server.send_signal(signal.SIGINT)
        try:
            server.wait(timeout=3)
        except subprocess.TimeoutExpired:
            server.kill()

    only_ml = sorted(p for p, _ in ml_found - stock_found)
    only_stock = sorted(p for p, _ in stock_found - ml_found)

    def row(label, found, stats, dt):
        reqs = stats.get("requests", 0)
        return (label, len(found), reqs, round(dt, 2),
                round(len(found) / reqs, 4) if reqs else 0.0)

    rows = [row("stock", stock_found, stock_stats, stock_dt),
            row("--ml", ml_found, ml_stats, ml_dt)]

    lines = []
    lines.append("| run | resources found | requests | wall (s) | found/req |")
    lines.append("|---|---:|---:|---:|---:|")
    for label, nf, reqs, dt, fpr in rows:
        lines.append(f"| {label} | {nf} | {reqs} | {dt} | {fpr} |")
    lines.append("")
    lines.append(f"**Found only with `--ml`** ({len(only_ml)}): "
                 + (", ".join(f"`{p}`" for p in only_ml) if only_ml else "_none_"))
    if only_stock:
        lines.append("")
        lines.append(f"**Found only by stock** ({len(only_stock)}): "
                     + ", ".join(f"`{p}`" for p in only_stock))
    report = "\n".join(lines)
    print(report)

    if args.out:
        header = (
            "# ML A/B benchmark\n\n"
            "Generated by [`scripts/ab_benchmark.py`](../../scripts/ab_benchmark.py) "
            f"against [`bench/{os.path.basename(args.server)}`](../../bench/{os.path.basename(args.server)}) "
            f"with [`bench/{os.path.basename(args.wordlist)}`](../../bench/{os.path.basename(args.wordlist)}).\n\n"
            f"Extra args applied to **both** runs: `{' '.join(args.extra) or '(none)'}`. "
            "The only difference between the two runs is `--ml`. See the server "
            "script for the (synthetic) ground-truth paths and why the nested "
            "convention tokens are intentionally absent from the wordlist — so the "
            "delta is purely the ML layer's prediction.\n\n"
        )
        notes = (
            "\n\n## Reading this\n\n"
            "- **`--ml` reaches paths stock cannot.** The ML-only finds are the "
            "`/api/v1` and `/api/v2` subtrees and `/users/me` — nested resources "
            "whose path tokens (`v1`, `v2`, `me`) are not in the wordlist. The "
            "layer fingerprints the target as `REST_API` and injects those tokens "
            "as per-directory predictions.\n"
            "- **It costs more requests.** `--ml` injects extra guesses per "
            "directory, so request count rises. A comparable `found/req` means "
            "those extra requests are about as productive as the base wordlist — "
            "they buy reach, not noise.\n"
            "- **Synthetic target.** `bench/structured_server.py` is a controlled "
            "illustration of the *mechanism*, not a yield claim about real targets. "
            "Run against your own authorized target to measure real-world lift.\n"
            "- **Stability.** The local Python server drops requests under high "
            "concurrency; use a low `-t` (e.g. `-t 10`) for repeatable counts. "
            "Deep-tree finds (e.g. `/api/v1/users/me`) can vary run to run as "
            "online learning order shifts.\n"
        )
        with open(args.out, "w") as fh:
            fh.write(header + report + notes)
        print(f"\nwrote {args.out}", file=sys.stderr)


if __name__ == "__main__":
    main()
